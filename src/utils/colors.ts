export const selectColor = (color: string) => {
  if (color === "red") return "#E67171";
  if (color === "cyan") return "#08a4a7";
  if (color === "pink") return "#FF91A4";
  if (color === "lightgreen") return "#53D253";
  if (color === "darkgreen") return "#135313";
  if (color === "purple") return "#9D00FF";
  if (color === "orange") return "#FFA500";
  if (color === "brown") return "#895129";
  if (color === "darkblue") return "#111184";
  if (color === "lightblue") return "#56BFFF";
};
